"""Shared media-input contract gate for image, video and mixed-media stages.

No inference, task-gold access, topology mutations or capability expansion.
Loader discovery/slot grouping are injected by the runtime adapter.
"""
from __future__ import annotations

from pathlib import Path
import re
from comfyrouter.closed_loop import ClosedLoopError, graph_output_reachable_nodes


class MediaInputError(ClosedLoopError):
    """A declared media boundary cannot be satisfied safely."""


def ordered_stage_resources(resources: list[Path], instruction: str = '') -> list[Path]:
    """Honor supplied filenames in the stage request before positional fallback.

    Only reorder supplied paths. Never resolve a named but unavailable file or
    treat a generated upstream artifact as a new original resource.
    """
    paths = list(dict.fromkeys(Path(p) for p in resources))
    positions = {}
    for path in paths:
        match = re.search(r'(?<![A-Za-z0-9_])' + re.escape(path.name)
                          + r'(?![A-Za-z0-9_])', instruction)
        if match:
            positions[path] = match.start()
    return sorted(paths, key=lambda p: (p not in positions, positions.get(p, paths.index(p))))


def external_media_resources(resources: list[Path], media_type: str) -> list[Path]:
    """Preserve resource order and distinguish paths, including external roots."""
    extensions = {
        "IMAGE": {".png", ".jpg", ".jpeg", ".webp", ".bmp"},
        "VIDEO": {".mp4", ".webm", ".mov", ".avi", ".gif"},
        "AUDIO": {".wav", ".mp3", ".flac", ".m4a"},
    }
    # MASK has no implicit external-image fallback: its role must be explicit
    # or it must be generated by a declared upstream stage.
    return list(dict.fromkeys(Path(p) for p in resources
                              if Path(p).suffix.lower() in extensions.get(media_type, set())))


class MediaInputGate:
    def __init__(self, *, nodes, groups, adapters, input_root: Path):
        self.nodes = nodes
        self.groups = groups
        self.adapters = adapters
        self.input_root = Path(input_root)

    def preflight(self, graph: dict, handoff_contract: dict,
                  *, case_resources: list[Path] | None = None,
                  validator=None) -> dict:
        """Fail closed when a required external media boundary is absent."""
        required_counts: dict[str, int] = {}
        for producer in handoff_contract.get("producer_dependencies", []):
            media_type = str(producer.get("media_type", "")).upper()
            if media_type in self.adapters:
                required_counts[media_type] = required_counts.get(media_type, 0) + 1
        upstream_counts = dict(required_counts)
        # A valid filename in the server's upload catalogue does not prove
        # that a template's saved mask belongs to this task. Reject leftover
        # masks even if another experiment left the file on the same server.
        if case_resources is not None and handoff_contract.get("required_input_types"):
            declared_mask = "MASK" in {
                str(kind).upper() for kind in handoff_contract["required_input_types"]
            } or upstream_counts.get("MASK", 0)
            supplied = {Path(path).name for path in case_resources}
            if not declared_mask:
                for node_id, field in self.nodes(graph, "MASK"):
                    node = graph[node_id]
                    value = node.get("inputs", {}).get(field)
                    derived = (node.get("_meta") or {}).get("comfyrouter_adapter")
                    if (isinstance(value, str) and Path(value).name not in supplied
                            and derived != "runtime_generated_geometry_mask"):
                        raise MediaInputError(
                            f"handoff_failed: unbound template MASK at node {node_id}: {value}; "
                            "this mask is neither a supplied task resource nor a declared upstream "
                            "artifact. Generate a source-aligned semantic mask from the current "
                            "image, or declare and bind a real upstream mask; never reuse a "
                            "previous task's saved mask."
                        )
        # Legacy callers only declare upstream boundaries. Production planning
        # also knows the external resources and must validate external roots and
        # repeated input types before any upstream inference is submitted.
        if case_resources is not None:
            for media_type in handoff_contract.get("required_input_types", []):
                media_type = str(media_type).upper()
                if media_type in self.adapters:
                    declared_count = sum(str(t).upper() == media_type for t in
                                         handoff_contract.get("required_input_types", []))
                    required_counts[media_type] = max(required_counts.get(media_type, 0), declared_count)
        reachable = graph_output_reachable_nodes(graph, validator) if validator is not None else None
        checks = []
        for media_type, required_count in required_counts.items():
            groups = self.groups(graph, media_type)
            available_count = len(groups)
            if available_count < required_count:
                raise MediaInputError(
                    f"handoff_failed: required {media_type} from upstream needs {required_count} "
                    f"compatible external loader(s), but the selected graph exposes {available_count}; "
                    "choose a matching complete Workflow Skill or add and connect the missing "
                    "media input before execution."
                )
            if reachable is not None:
                disconnected = [node_id for group in groups for node_id, _ in group
                                if node_id not in reachable]
                if disconnected:
                    raise MediaInputError(
                        f"handoff_failed: required {media_type} loader(s) "
                        + ", ".join(disconnected) + " do not contribute to an output; "
                        "adding file readers alone does not establish a usable input."
                    )
            external_count = required_count - upstream_counts.get(media_type, 0)
            if case_resources is not None and external_count:
                sources = external_media_resources(case_resources, media_type)
                if len(sources) < external_count:
                    raise MediaInputError(
                        f"handoff_failed: required {media_type} needs {external_count} external "
                        f"resource(s), but only {len(sources)} were supplied; do not reuse the first "
                        "file as an independent second input or invent an upstream artifact."
                    )
                missing_files = [str(path) for path in sources[:external_count] if not path.is_file()]
                if missing_files:
                    raise MediaInputError(
                        f"handoff_failed: required {media_type} external resource file(s) are missing: "
                        + ", ".join(missing_files)
                    )
            checks.append({"media_type": media_type, "required_slots": required_count,
                           "available_slots": available_count,
                           "upstream_slots": upstream_counts.get(media_type, 0),
                           "external_slots": external_count})
        requirement = handoff_contract.get("mask_requirement", {})
        if str(requirement.get("status")).casefold() != "required":
            return {"status": "interface_checked_artifacts_pending", "inputs": checks,
                    "output_connectivity_checked": reachable is not None}
        mask_inputs = self.nodes(graph, "MASK")
        if mask_inputs:
            return {"status": "interface_checked_artifacts_pending", "inputs": checks,
                    "output_connectivity_checked": reachable is not None}
        raise MediaInputError(
            "handoff_failed: required MASK has no compatible external loader in the selected graph; "
            "choose a matching complete Workflow Skill or a mask-aware leaf, preserving the upstream "
            "MASK contract."
        )


    def bind_external(self, graph: dict, input_types, resources: list[Path],
                      used_by_type: dict[str, int], *, instruction: str = '') -> list[dict]:
        """Bind each remaining declared slot once; never fan two files into one slot."""
        bindings = []
        resources = ordered_stage_resources(resources, instruction)
        for media_type in dict.fromkeys(input_types):
            if media_type not in self.adapters:
                continue
            declared = input_types.count(media_type)
            used = used_by_type.get(media_type, 0)
            required = max(0, declared - used)
            if not required:
                continue
            sources = external_media_resources(resources, media_type)
            groups = self.groups(graph, media_type)
            if len(sources) < required or len(groups) < used + required:
                raise MediaInputError(
                    f"handoff_failed: required {media_type} has {required} unfilled external slot(s); "
                    f"supplied resources={len(sources)}, available slots={max(0, len(groups)-used)}"
                )
            if len({source.name for source in sources[:required]}) != required:
                raise MediaInputError(
                    f"handoff_failed: required {media_type} resources have colliding filenames; "
                    "materialize distinct input aliases before binding"
                )
            for index, (group, source) in enumerate(zip(groups[used:used + required], sources[:required]), used + 1):
                for node_id, input_name in group:
                    graph[node_id].setdefault('_meta', {}).setdefault('comfyrouter_handoff', {
                        'media_type': media_type, 'slot': f'{media_type}_external_slot_{index:02d}',
                    })
                    graph[node_id].setdefault("inputs", {})[input_name] = source.name
                    bindings.append({"source": str(source), "input": str(source),
                                     "node_id": node_id, "input_name": input_name,
                                     "media_type": media_type, "kind": "case_resource"})
        return bindings


    def inspect_materialized(self, graph: dict, media_types) -> dict:
        """Decode materialized inputs before GPU work; reject known batch conflicts.

        This proves file/loader compatibility, not task semantics. Unknown custom
        transformations remain subject to node validation and actual execution.
        """
        from PIL import Image
        import cv2
        records = []
        dimensions = {}
        for media_type in dict.fromkeys(media_types):
            for node_id, key in self.nodes(graph, media_type):
                node = graph[node_id]
                value = node['inputs'][key]
                path = Path(value) if Path(value).is_absolute() else self.input_root / value
                if not path.is_file():
                    raise MediaInputError(f"handoff_failed: required {media_type} file is missing: {path}")
                metadata = {"node_id": node_id, "media_type": media_type, "path": str(path)}
                image_extensions = {'.png', '.jpg', '.jpeg', '.webp', '.bmp'}
                video_extensions = {'.mp4', '.webm', '.mov', '.avi', '.gif'}
                video_loader = node.get('class_type') in {'LoadVideo', 'VHS_LoadVideo'}
                if (media_type == 'IMAGE' and path.suffix.lower() not in image_extensions
                        or media_type == 'VIDEO' and path.suffix.lower() not in video_extensions
                        or media_type == 'MASK' and path.suffix.lower() not in
                        (video_extensions if video_loader else image_extensions)):
                    raise MediaInputError(
                        f"handoff_failed: {media_type} input {path} has an incompatible "
                        f"container for loader {node.get('class_type')}"
                    )
                if path.suffix.lower() in image_extensions:
                    try:
                        with Image.open(path) as image:
                            image.load()
                            width, height = image.size
                            metadata.update(width=width, height=height)
                    except (OSError, ValueError) as exc:
                        raise MediaInputError(f"handoff_failed: cannot decode {media_type} input {path}: {exc}") from exc
                    if node.get('class_type') == 'LoadImage':
                        dimensions[(node_id, 0)] = (width, height)
                elif path.suffix.lower() in video_extensions:
                    capture = cv2.VideoCapture(str(path))
                    try:
                        ok, frame = capture.read()
                        count = int(capture.get(cv2.CAP_PROP_FRAME_COUNT))
                        fps = float(capture.get(cv2.CAP_PROP_FPS))
                    finally:
                        capture.release()
                    if not ok or fps <= 0 or count < 1:
                        raise MediaInputError(f"handoff_failed: cannot decode {media_type} video input {path}")
                    height, width = frame.shape[:2]
                    metadata.update(width=width, height=height, frames=count, fps=fps, duration=count/fps)
                    if node.get('class_type') == 'VHS_LoadVideo':
                        inputs = node['inputs']
                        rate = inputs.get('force_rate', 0)
                        loaded_count = round(count * rate / fps) if isinstance(rate, (int, float)) and rate > 0 else count
                        skip = inputs.get('skip_first_frames', 0)
                        if isinstance(skip, (int, float)) and skip >= loaded_count:
                            raise MediaInputError(
                                f"handoff_failed: video loader {node_id} skips {skip} frames "
                                f"but input provides approximately {loaded_count}; no frames remain"
                            )
                        custom_width, custom_height = inputs.get('custom_width', 0), inputs.get('custom_height', 0)
                        if custom_width == 0 and custom_height == 0:
                            dimensions[(node_id, 0)] = (width, height)
                        elif all(isinstance(v, (int, float)) and v > 0 for v in (custom_width, custom_height)):
                            dimensions[(node_id, 0)] = (int(custom_width), int(custom_height))
                records.append(metadata)
        # Direct ImageBatch is the current two-clip assembly interface. A pair of
        # valid video loaders is insufficient when their IMAGE batches cannot join.
        checked_batches, deferred_batches = [], []
        for node_id, node in graph.items():
            if node.get('class_type') != 'ImageBatch':
                continue
            refs = [node.get('inputs', {}).get(key) for key in ('image1', 'image2')]
            shapes = [dimensions.get((str(ref[0]), ref[1]))
                      if isinstance(ref, list) and len(ref) == 2 else None for ref in refs]
            if all(shapes):
                if shapes[0] != shapes[1]:
                    raise MediaInputError(
                        f"handoff_failed: ImageBatch {node_id} input canvases differ: "
                        f"{shapes[0]} vs {shapes[1]}; add an explicit compatible resize/pad "
                        "before assembly, preserving the task requirements"
                    )
                checked_batches.append(str(node_id))
            else:
                deferred_batches.append(str(node_id))
        return {"status": "materialized_inputs_checked", "inputs": records,
                "direct_batch_geometry_checked": checked_batches,
                "batch_geometry_requires_execution": deferred_batches,
                "semantic_compatibility": "requires_output_evaluation"}
